-- Customer-visible semantic surface.
-- CUSTOMER_ACCESS is intentionally empty by default: populate explicit role/customer
-- mappings before granting this view to PORTPILOT_CUSTOMER_SUCCESS.
CREATE TABLE IF NOT EXISTS PORTPILOT.GOVERNANCE.CUSTOMER_ACCESS (
  role_name STRING NOT NULL,
  customer_id STRING NOT NULL,
  CONSTRAINT CUSTOMER_ACCESS_PK PRIMARY KEY (role_name, customer_id)
);

