CREATE OR REPLACE SECURE VIEW PORTPILOT.SEMANTIC.V_CONTAINER_JOURNEY AS
SELECT j.container_id, j.booking_date, j.customer_id,
  c.tier AS customer_tier,
  CASE WHEN IS_ROLE_IN_SESSION('PORTPILOT_OPS_ANALYST') OR IS_ROLE_IN_SESSION('PORTPILOT_AUDITOR')
       THEN c.contact_email ELSE '***MASKED***' END AS contact_email,
  j.trade_lane, j.vessel_id, j.on_time_delivery, j.delay_hours, j.documentation_late,
  j.routed_through_sgsin, WEEKISO(j.booking_date) AS iso_week
FROM PORTPILOT.RAW.FACT_CONTAINER_JOURNEY j
JOIN PORTPILOT.RAW.DIM_CUSTOMER c ON c.customer_id = j.customer_id
WHERE IS_ROLE_IN_SESSION('PORTPILOT_OPS_ANALYST') OR IS_ROLE_IN_SESSION('PORTPILOT_EXEC')
   OR IS_ROLE_IN_SESSION('PORTPILOT_AUDITOR') OR IS_ROLE_IN_SESSION('PORTPILOT_ENGINEER')
   OR EXISTS (SELECT 1 FROM PORTPILOT.GOVERNANCE.CUSTOMER_ACCESS a
              WHERE a.customer_id = j.customer_id AND a.role_name = CURRENT_ROLE());

CREATE OR REPLACE SECURE VIEW PORTPILOT.SEMANTIC.V_DELAY_EVENT AS
SELECT d.container_id, d.cause_code, d.delay_hours, d.event_date,
       WEEKISO(d.event_date) AS iso_week, j.trade_lane
FROM PORTPILOT.RAW.FACT_DELAY_EVENT d
JOIN PORTPILOT.RAW.FACT_CONTAINER_JOURNEY j ON j.container_id = d.container_id;

CREATE OR REPLACE TABLE PORTPILOT.SEMANTIC.EVENT_VOLUME_DAILY AS
SELECT TO_DATE(event_at_utc) AS event_day, source_system, event_type, COUNT(*) AS event_count
FROM PORTPILOT.RAW.FACT_CONTAINER_EVENT GROUP BY 1, 2, 3;

