-- Truth #1/#6: APAC OTD dips in week 33
SELECT iso_week, ROUND(100*AVG(on_time_delivery),1) AS otd_pct
FROM PORTPILOT.SEMANTIC.V_CONTAINER_JOURNEY
WHERE trade_lane IN ('APAC_DOMESTIC','NORTH_ASIA','TRANS_TASMAN') AND iso_week BETWEEN 30 AND 36
GROUP BY 1 ORDER BY 1;

-- Week-33 causes
SELECT cause_code, COUNT(*) AS events FROM PORTPILOT.SEMANTIC.V_DELAY_EVENT
WHERE iso_week = 33 AND trade_lane IN ('APAC_DOMESTIC','NORTH_ASIA','TRANS_TASMAN')
GROUP BY 1 ORDER BY 2 DESC;

-- Truth #5: Rotterdam GATE_OUT = 0 on Sep 1-3, other feeds steady
SELECT event_day,
  SUM(IFF(source_system='TOS_ROTTERDAM' AND event_type='GATE_OUT', event_count, 0)) AS rotterdam_gate_out,
  SUM(IFF(source_system<>'TOS_ROTTERDAM' AND event_type='GATE_OUT', event_count, 0)) AS other_gate_out
FROM PORTPILOT.SEMANTIC.EVENT_VOLUME_DAILY
WHERE event_day BETWEEN '2026-08-31' AND '2026-09-04' GROUP BY 1 ORDER BY 1;

